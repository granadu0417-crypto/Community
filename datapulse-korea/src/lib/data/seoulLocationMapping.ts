/**
 * 검색어를 기반으로 구 이름 찾기
 * @param query 검색어
 * @returns 매핑된 구 이름 또는 null
 */
export function findDistrictByKeyword(query: string): string | null {
  const normalizedQuery = query.trim().toLowerCase()

  // 직접 매핑된 키워드 찾기
  for (const [keyword, district] of Object.entries(DISTRICT_MAPPINGS)) {
    if (keyword.toLowerCase() === normalizedQuery || keyword.toLowerCase().includes(normalizedQuery)) {
      return district
    }
  }

  return null
}

/**
 * 검색어와 관련된 모든 구 이름 찾기 (다중 매칭)
 * @param query 검색어
 * @returns 매핑된 구 이름 배열
 */
export function findAllDistrictsByKeyword(query: string): string[] {
  const normalizedQuery = query.trim().toLowerCase()
  const districts = new Set<string>()

  // 매핑된 모든 키워드 검색
  for (const [keyword, district] of Object.entries(DISTRICT_MAPPINGS)) {
    if (keyword.toLowerCase().includes(normalizedQuery) || normalizedQuery.includes(keyword.toLowerCase())) {
      districts.add(district)
    }
  }

  return Array.from(districts)
}
